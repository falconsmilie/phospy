def test_fixture_d_retains_valid_consensus_with_feature_level_failures() -> None:
    fixture_id = "fixture_d_feature_level_failures"
    base = FIXTURE_ROOT / fixture_id
    correlations = _csv(base / "feature_correlations.csv")
    feature_metadata = _csv(base / "feature_metadata.csv")
    summary = _summary(fixture_id)
    ebayes = _csv(base / "ebayes_statistics.csv")

    assert feature_metadata["controlled_case"].tolist() == [
        "valid_null",
        "valid_non_null",
        "missing_observations_but_estimable",
        "constant_feature",
        "near_constant_feature",
        "feature_specific_rank_loss",
        "insufficient_observed_values",
        "all_observations_missing",
    ]
    assert int(summary["estimated_feature_correlation_count"]) == 4
    assert int(summary["missing_feature_correlation_count"]) == 4
    assert math.isfinite(float(summary["consensus_correlation"]))
    assert set(correlations["atanh_correlation_missing_kind"]) == {
        "finite",
        "NA",
        "NaN",
    }

    valid_rows = ebayes["feature_id"].isin(
        ["D_valid_null", "D_valid_effect", "D_missing_still_estimable"]
    )
    for column in PUBLIC_STATISTIC_COLUMNS:
        assert _numeric(ebayes.loc[valid_rows, column]).notna().all()
    invalid_rows = ebayes["feature_id"].isin(
        ["D_rank_loss_only_A", "D_insufficient_one", "D_all_missing"]
    )
    for column in PUBLIC_STATISTIC_COLUMNS:
        assert (ebayes.loc[invalid_rows, column] == "NA").all()
