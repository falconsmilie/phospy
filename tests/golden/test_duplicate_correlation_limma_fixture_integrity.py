def _manifest() -> dict[str, Any]:
    payload = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    assert isinstance(payload, dict)
    return payload


def _fixture_entry(fixture_id: str) -> dict[str, Any]:
    for entry in _manifest()["fixtures"]:
        if entry["id"] == fixture_id:
            assert isinstance(entry, dict)
            return entry
    raise AssertionError(f"unknown duplicate-correlation fixture {fixture_id!r}")


def _csv(path: Path) -> pd.DataFrame:
    return pd.read_csv(path, keep_default_na=False)


def _numeric(series: pd.Series) -> pd.Series:
    return pd.to_numeric(series.replace("NA", pd.NA), errors="coerce")


def _summary(fixture_id: str) -> dict[str, str]:
    frame = _csv(FIXTURE_ROOT / fixture_id / "duplicate_correlation_summary.csv")
    assert list(frame.columns) == ["field", "value"]
    return dict(zip(frame["field"], frame["value"], strict=True))


def _file_sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _assert_residual_variance_matches_sigma(frame: pd.DataFrame) -> None:
    sigma = _numeric(frame["sigma"])
    residual_variance = _numeric(frame["residual_variance"])
    finite = sigma.notna() & residual_variance.notna()
    np.testing.assert_allclose(
        residual_variance.loc[finite].to_numpy(dtype=float),
        sigma.loc[finite].to_numpy(dtype=float) ** 2,
        rtol=1e-12,
        atol=1e-18,
    )
    assert residual_variance.loc[sigma.isna()].isna().all()


