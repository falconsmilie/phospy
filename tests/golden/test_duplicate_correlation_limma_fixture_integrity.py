def test_duplicate_correlation_limma_manifest_hashes_match_fixture_bytes() -> None:
    manifest = _manifest()

    seen_paths: set[str] = set()
    for item in manifest["files"]:
        relative_path = item["relative_path"]
        assert relative_path not in seen_paths
        seen_paths.add(relative_path)
        assert item["role"] in {"input", "intermediate", "output", "governance"}
        assert SHA256_RE.fullmatch(item["sha256"])
        path = FIXTURE_ROOT / relative_path
        assert path.is_file(), relative_path
        assert _file_sha256(path) == item["sha256"]

    for fixture_id in EXPECTED_FIXTURE_IDS:
        present = {
            Path(item["relative_path"]).name
            for item in manifest["files"]
            if item["fixture"] == fixture_id
        }
        assert present == REQUIRED_FIXTURE_FILES


def test_duplicate_correlation_limma_fixture_parity_scopes_cover_manifest_once() -> (
    None
):
    manifest_fixture_ids = tuple(str(entry["id"]) for entry in _manifest()["fixtures"])
    assert Counter(manifest_fixture_ids) == {
        fixture_id: 1 for fixture_id in manifest_fixture_ids
    }

    committed_fixture_dirs = tuple(
        sorted(path.name for path in FIXTURE_ROOT.iterdir() if path.is_dir())
    )
    assert set(committed_fixture_dirs) == set(manifest_fixture_ids)

    fixture_id_set = set(manifest_fixture_ids)
    assignments = {fixture_id: [] for fixture_id in manifest_fixture_ids}
    unknown_assignments: list[str] = []
    for scope, fixture_ids in DUPLICATE_CORRELATION_PARITY_SCOPE_FIXTURE_IDS.items():
        for fixture_id in fixture_ids:
            if fixture_id not in fixture_id_set:
                unknown_assignments.append(fixture_id)
                continue
            assignments[fixture_id].append(scope)

    unclassified = [
        fixture_id for fixture_id, scopes in assignments.items() if not scopes
    ]
    conflicting = {
        fixture_id: [scope.value for scope in scopes]
        for fixture_id, scopes in assignments.items()
        if len(scopes) != 1
    }
    assert unknown_assignments == []
    assert unclassified == []
    assert conflicting == {}

    assert FULL_PIPELINE_FIXTURE_IDS == (
        "fixture_a_complete_pairs",
        "fixture_b_three_observation_blocks",
        "fixture_c_incomplete_unequal_blocks",
    )
    assert ESTIMATOR_AND_GLS_ONLY_FIXTURE_IDS == ("fixture_d_feature_level_failures",)
    assert (
        DUPLICATE_CORRELATION_FIXTURE_PARITY_SCOPES["fixture_d_feature_level_failures"]
        is DuplicateCorrelationParityScope.ESTIMATOR_AND_GLS_ONLY
    )
    for fixture_id in FULL_PIPELINE_FIXTURE_IDS:
        assert (
            DUPLICATE_CORRELATION_FIXTURE_PARITY_SCOPES[fixture_id]
            is DuplicateCorrelationParityScope.FULL_PIPELINE
        )


@pytest.mark.parametrize("fixture_id", EXPECTED_FIXTURE_IDS)
def test_duplicate_correlation_limma_fixture_schema_and_order(
    fixture_id: str,
) -> None:
    entry = _fixture_entry(fixture_id)
    base = FIXTURE_ROOT / fixture_id
    sample_ids = list(entry["sample_ids"])
    feature_ids = list(entry["feature_ids"])
    design_columns = list(entry["design_columns"])
    contrast_names = list(entry["contrast_names"])

    sample_metadata = _csv(base / "sample_metadata.csv")
    assert list(sample_metadata.columns)[:4] == [
        "sample_order",
        "sample_id",
        "block_id",
        "condition",
    ]
    assert sample_metadata["sample_id"].tolist() == sample_ids
    assert _numeric(sample_metadata["sample_order"]).tolist() == list(
        range(1, len(sample_ids) + 1)
    )

    matrix = _csv(base / "matrix.csv")
    assert list(matrix.columns) == ["feature_id", *sample_ids]
    assert matrix["feature_id"].tolist() == feature_ids

    design = _csv(base / "design.csv")
    assert list(design.columns) == ["sample_id", *design_columns]
    assert design["sample_id"].tolist() == sample_ids
    assert not any("block" in column.lower() for column in design_columns)
    assert np.linalg.matrix_rank(design.loc[:, design_columns].astype(float)) == len(
        design_columns
    )

    contrasts = _csv(base / "contrasts.csv")
    assert list(contrasts.columns) == ["coefficient", *contrast_names]
    assert contrasts["coefficient"].tolist() == design_columns

    feature_metadata = _csv(base / "feature_metadata.csv")
    assert feature_metadata["feature_id"].tolist() == feature_ids
    assert _numeric(feature_metadata["feature_order"]).tolist() == list(
        range(1, len(feature_ids) + 1)
    )

    correlations = _csv(base / "feature_correlations.csv")
    assert list(correlations.columns) == [
        "feature_order",
        "feature_id",
        "atanh_correlation",
        "correlation",
        "status",
        "atanh_correlation_missing_kind",
        "observed_value_count",
        "design_rank",
        "fixture",
    ]
    assert correlations["feature_id"].tolist() == feature_ids
    assert set(correlations["status"]) <= {"estimated", "missing"}
    assert set(correlations["atanh_correlation_missing_kind"]) <= {
        "finite",
        "NA",
        "NaN",
    }
    estimated = correlations["status"] == "estimated"
    assert _numeric(correlations.loc[estimated, "atanh_correlation"]).notna().all()
    assert _numeric(correlations.loc[estimated, "correlation"]).notna().all()
    assert (correlations.loc[~estimated, "atanh_correlation"] == "NA").all()
    assert (correlations.loc[~estimated, "correlation"] == "NA").all()

    assert list(_csv(base / "fit_coefficients.csv").columns) == [
        "feature_id",
        *design_columns,
    ]
    assert list(_csv(base / "fit_stdev_unscaled.csv").columns) == [
        "feature_id",
        *design_columns,
    ]
    assert list(_csv(base / "fit_cov_coefficients.csv").columns) == [
        "coefficient",
        *design_columns,
    ]
    fit_sigma = _csv(base / "fit_sigma_df.csv")
    assert list(fit_sigma.columns) == [
        "feature_id",
        "sigma",
        "residual_variance",
        "residual_degrees_of_freedom",
        "average_expression",
    ]
    assert fit_sigma["feature_id"].tolist() == feature_ids
    _assert_residual_variance_matches_sigma(fit_sigma)

    assert list(_csv(base / "contrast_fit_coefficients.csv").columns) == [
        "feature_id",
        *contrast_names,
    ]
    assert list(_csv(base / "contrast_fit_stdev_unscaled.csv").columns) == [
        "feature_id",
        *contrast_names,
    ]
    assert list(_csv(base / "contrast_fit_cov_coefficients.csv").columns) == [
        "contrast",
        *contrast_names,
    ]

    ebayes = _csv(base / "ebayes_statistics.csv")
    assert list(ebayes.columns) == [
        "feature_id",
        "contrast",
        *PUBLIC_STATISTIC_COLUMNS[:1],
        "AveExpr",
        "SE",
        *PUBLIC_STATISTIC_COLUMNS[1:],
        "B",
        "stdev.unscaled",
        "sigma",
        "residual_degrees_of_freedom",
        "s2.prior",
        "df.prior",
        "s2.post",
        "df.total",
        "var.prior",
        "proportion",
    ]
    assert set(ebayes["contrast"]) == set(contrast_names)
    assert ebayes["feature_id"].tolist() == feature_ids * len(contrast_names)

    priors = _csv(base / "ebayes_priors.csv")
    assert list(priors.columns) == [
        "feature_id",
        "sigma",
        "residual_variance",
        "residual_degrees_of_freedom",
        "s2.prior",
        "df.prior",
        "s2.post",
        "df.total",
        "average_expression",
    ]
    assert priors["feature_id"].tolist() == feature_ids
    _assert_residual_variance_matches_sigma(priors)

    summary = _summary(fixture_id)
    assert summary["fixture"] == fixture_id
    assert int(summary["sample_count"]) == len(sample_ids)
    assert int(summary["feature_count"]) == len(feature_ids)
    assert int(summary["estimated_feature_correlation_count"]) == int(
        entry["estimated_feature_correlation_count"]
    )
    assert int(summary["missing_feature_correlation_count"]) == int(
        entry["missing_feature_correlation_count"]
    )


